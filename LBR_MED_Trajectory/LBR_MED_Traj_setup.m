%% LBR_MED_Traj_setup.m
% Phase 2 – Trajectory Execution with Remote Centre of Motion (Trocar) Constraint
%
% A rigid biopsy-needle tool (length L = 15 cm) is attached at the EE.
% The tool is inserted through a trocar at FIXED position c_r.
% The CLIK controller drives the tooltip to a list of surgical targets
% while the RCM constraint is satisfied by design.

this_dir     = fileparts(mfilename('fullpath'));
project_root = fileparts(this_dir);

addpath(fullfile(project_root, 'LBR_MED_DKin'));
addpath(fullfile(project_root, 'LBR_MED_CLIK'));
addpath(fullfile(project_root, 'LBR_MED_IK_Analytical'));
addpath(fullfile(project_root, 'Robotics_Symbolic_Matlab_Toolbox-2'));
addpath(this_dir);

%% 1. Load symbolic models (generated by Phase 1 CLIK setup)
fprintf('Loading symbolic kinematic models...\n');
mat_file = fullfile(project_root, 'LBR_MED_CLIK', 'LBR_MED_symbolic.mat');
if ~exist(mat_file, 'file')
    error('Symbolic .mat not found. Run LBR_MED_CLIK_setup.m first.');
end
load(mat_file, 'R_sym', 'p_sym', 'J', 'vars');

Robot = LBR_MED();
n     = size(Robot, 1);   % 7

q_vec   = sym('q', [n, 1], 'real');
p_sym_v = subs(p_sym, vars.', q_vec);
R_sym_v = subs(R_sym, vars.', q_vec);
J_v     = subs(J,     vars.', q_vec);

fprintf('Building numeric functions from symbolic expressions...\n');
dk_fun = matlabFunction(p_sym_v, R_sym_v, 'Vars', {q_vec});
J_fun  = matlabFunction(J_v,             'Vars', {q_vec});
fprintf('Numeric functions ready.\n\n');

%% 2. Surgical scenario: trocar and target list
L_tool = 0.15;                    % tool length (m)
c_r    = [-0.6; 0.0; 0.55];      % trocar (RCM) position in robot base frame

% Five targets, all within 10 cm of trocar  (must satisfy ||m - c_r|| < L_tool)
targets = [
    c_r + [0.00;  0.00; -0.08], ...
    c_r + [0.06;  0.00; -0.07], ...
    c_r + [-0.05; 0.04; -0.07], ...
    c_r + [0.02; -0.05; -0.09], ...
    c_r + [0.00;  0.00; -0.06]  ...
];   % 3×5

N_t = size(targets, 2);

%% 3. Compute desired EE poses (RCM constraint applied here)
fprintf('Computing EE poses from RCM constraint:\n');
p_des_list = zeros(3, N_t);
R_des_list = zeros(3, 3, N_t);
for i = 1:N_t
    [p_des_list(:,i), R_des_list(:,:,i)] = compute_ee_pose_rcm(targets(:,i), c_r, L_tool);
    fprintf('  Target %d: m=[%.3f, %.3f, %.3f]  p_ee=[%.3f, %.3f, %.3f]\n', ...
        i, targets(1,i), targets(2,i), targets(3,i), ...
        p_des_list(1,i), p_des_list(2,i), p_des_list(3,i));
end

%% 4. CLIK parameters (consistent with Phase 1)
K_pos  = 10;
K_ori  = 5;
Kn_val = 3;
dt     = 0.005;      % integration step (s)
T_pt   = 3.0;        % seconds spent per target
q_rest = zeros(n, 1);

% Initial configuration: analytical IK for first target
q0 = LBR_MED_IK(p_des_list(:,1), R_des_list(:,:,1), []);
if isempty(q0) || any(isnan(q0))
    q0 = [pi; 0.5; 0; -0.9; 0; 1.2; 0];
    fprintf('\nFallback q0 used (analytical IK failed).\n');
else
    fprintf('\nInitial q0 from analytical IK.\n');
end

%% 5. MATLAB CLIK simulation (forward-Euler integration)
fprintf('\nRunning CLIK trajectory simulation (%d targets × %.1f s each)...\n', N_t, T_pt);

t_vec   = 0 : dt : N_t * T_pt;
N_steps = length(t_vec);

q_log          = zeros(n, N_steps);
tip_log        = zeros(3, N_steps);
trocar_err_log = zeros(1, N_steps);
pos_err_log    = zeros(1, N_steps);
tgt_log        = zeros(1, N_steps);

q_curr = q0(:);

for k = 1:N_steps
    t   = t_vec(k);
    idx = min(floor(t / T_pt) + 1, N_t);

    p_des = p_des_list(:, idx);
    R_des = R_des_list(:, :, idx);

    [p_curr, R_curr] = dk_fun(q_curr);
    J_curr           = double(J_fun(q_curr));

    % Tooltip position and RCM constraint error
    a_ee      = R_curr(:, 3);
    p_tip     = p_curr + L_tool * a_ee;
    v         = c_r - p_curr;
    trocar_err = norm(v - dot(v, a_ee) * a_ee);  % perpendicular dist from c_r to tool axis

    q_log(:, k)       = q_curr;
    tip_log(:, k)     = p_tip;
    trocar_err_log(k) = trocar_err;
    pos_err_log(k)    = norm(p_tip - targets(:, idx));
    tgt_log(k)        = idx;

    q_dot  = clik_controller_logic(p_des, R_des, p_curr, R_curr, ...
                                    J_curr, q_curr, q_rest, K_pos, K_ori, Kn_val);
    q_curr = q_curr + dt * q_dot;
end

%% 6. Validation summary
fprintf('\n=== Phase 2 Validation ===\n');
fprintf('%-10s %-18s %-18s\n', 'Target', 'Tip error (m)', 'Trocar error (m)');
for i = 1:N_t
    k_end = find(tgt_log == i, 1, 'last');
    if ~isempty(k_end)
        fprintf('  %d         %-18.4e %-18.4e\n', i, pos_err_log(k_end), trocar_err_log(k_end));
    end
end

%% 7. Plots
% --- Joint trajectories ---
figure('Name', 'Phase 2 – Joint Trajectories');
plot(t_vec, q_log', 'LineWidth', 1.5);
hold on;
for i = 1:N_t-1
    xline(i*T_pt, 'k--');
end
title('Joint Trajectories: RCM Surgical Trajectory');
xlabel('Time (s)'); ylabel('q (rad)');
legend({'q_1','q_2','q_3','q_4','q_5','q_6','q_7'}, 'Location', 'best');
grid on;

% --- 3-D tooltip path ---
figure('Name', 'Phase 2 – 3D Tooltip Trajectory');
plot3(tip_log(1,:), tip_log(2,:), tip_log(3,:), 'b-', 'LineWidth', 1.5);
hold on;
scatter3(targets(1,:), targets(2,:), targets(3,:), 150, 'r*', 'LineWidth', 2);
plot3(c_r(1), c_r(2), c_r(3), 'ko', 'MarkerSize', 15, 'MarkerFaceColor', 'k');
for i = 1:N_t
    text(targets(1,i)+0.005, targets(2,i), targets(3,i)-0.005, ...
         sprintf(' m_%d', i), 'FontSize', 10, 'Color', 'r');
end
legend({'Tooltip path', 'Targets $m_i$', 'Trocar $c_r$'}, ...
       'Interpreter', 'latex', 'Location', 'best');
title('Tooltip 3D Trajectory with RCM Constraint');
xlabel('X (m)'); ylabel('Y (m)'); zlabel('Z (m)');
grid on; axis equal;

% --- Error convergence ---
figure('Name', 'Phase 2 – Convergence & Constraint');
subplot(2,1,1);
semilogy(t_vec, pos_err_log + 1e-12, 'b', 'LineWidth', 1.5);
for i = 1:N_t-1, xline(i*T_pt, 'k--'); end
title('Tooltip Position Error  \|p_{tip} - m_i\|');
xlabel('Time (s)'); ylabel('Error (m)'); grid on;

subplot(2,1,2);
semilogy(t_vec, trocar_err_log + 1e-12, 'r', 'LineWidth', 1.5);
for i = 1:N_t-1, xline(i*T_pt, 'k--'); end
title('Trocar Constraint Violation  dist(c_r, tool axis)');
xlabel('Time (s)'); ylabel('Distance (m)'); grid on;

fprintf('\nPhase 2 setup complete.\n');
cd(project_root);
